def blur1(M, r):
    kk = np.ones(2 * r + 1, dtype=np.float32) / (2 * r + 1)
    M = np.apply_along_axis(lambda v: np.convolve(v, kk, mode='same'), 1, M)
    return np.apply_along_axis(lambda v: np.convolve(v, kk, mode='same'), 0, M)


def text_mask(text, cw, ch, gap=1.0):
    """Маска строки (float 0…1, строка сверху): клетка шрифта cw × ch пикселей листа, между буквами gap клеток; сглаживание — размытие и мягкий порог."""
    cs = 12                                                       # клетка шрифта в целых пикселях при рисовании (дальше масштаб до cw × ch — без щелей между клетками)
    gp = int(round(gap * cs)); pad = 2 * cs
    cols = len(text) * 5 + (len(text) - 1) * gap
    a = np.zeros((7 * cs + 2 * pad, int(round(cols * cs)) + 2 * pad), dtype=np.float32)
    for n, c in enumerate(text):
        g = GLYPH[c]
        for r in range(7):
            for q in range(5):
                if g[r][q] != '#': continue
                x0 = pad + n * (5 * cs + gp) + q * cs; y0 = pad + r * cs
                a[y0:y0 + cs, x0:x0 + cs] = 1.0
    a = np.clip((blur1(blur1(a, 3), 2) - 0.5) / 0.20 + 0.5, 0.0, 1.0)          # сглаживание «пикселей»: скруглённые углы, ровные диагонали
    Wp, Hp = int(round(cols * cw + 2 * pad * cw / cs)), int(round(7 * ch + 2 * pad * ch / cs))
    im = Image.fromarray((a * 255).astype(np.uint8)).resize((Wp, Hp), Image.LANCZOS)
    return np.asarray(im, dtype=np.float32) / 255.0


class Sheet:
    def __init__(self, mirror):
        self.mirror = mirror
        self.ch = {k: Image.new('L', (W * SS, H * SS), 0) for k in 'RGBA'}
        self.dr = {k: ImageDraw.Draw(im) for k, im in self.ch.items()}

    def T(self, x, y):
        xx = (2 * X0 - x) if self.mirror else x
        return ((xx - X_MIN) * K * SS, (y - Y_MIN) * K * SS)

    def poly(self, ch, pts, val=255): self.dr[ch].polygon([self.T(x, y) for x, y in pts], fill=val)

    def line(self, ch, pts, w, val=255):
        P = [self.T(x, y) for x, y in pts]
        self.dr[ch].line(P, fill=val, width=max(1, int(round(w * K * SS))), joint='curve')
        for p in (P[0], P[-1]): r = w * K * SS / 2; self.dr[ch].ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=val)

    def circle(self, ch, cx, cy, r, val=255, ring=None):
        px, py = self.T(cx, cy); R = r * K * SS
        if ring is None: self.dr[ch].ellipse([px - R, py - R, px + R, py + R], fill=val)
        else: self.dr[ch].ellipse([px - R, py - R, px + R, py + R], outline=val, width=max(1, int(round(ring * K * SS))))

    def text(self, ch, s, cx, cy, h_px, w_px, gap=1.0, val=1.0, block=None):
        """Строка s по центру (cx, cy) чертежа: высота букв h_px, общая ширина w_px (пикс. чертежа). Позиция зеркалится на правом борту, буквы — нет;
        block — x середины блока из нескольких строк («USAF» + «AN/ALQ-131(V)-12»): на правом борту зеркалится блок целиком, порядок слов слева направо остаётся."""
        if self.mirror and block is not None: cx = 2 * block - cx                # T() сам отзеркалит: итог x' = 2·X0 − 2·block + cx
        cols = len(s) * 5 + (len(s) - 1) * gap
        m = text_mask(s, w_px * K / cols, h_px * K / 7.0, gap)
        px, py = self.T(cx, cy); x0, y0 = int(round(px / SS - m.shape[1] / 2)), int(round(py / SS - m.shape[0] / 2))
        self.tx = getattr(self, 'tx', {k: np.zeros((H, W), dtype=np.float32) for k in 'RGBA'})
        T_ = self.tx[ch]; ys, xs = max(0, y0), max(0, x0); ye, xe = min(H, y0 + m.shape[0]), min(W, x0 + m.shape[1])
        T_[ys:ye, xs:xe] = np.maximum(T_[ys:ye, xs:xe], m[ys - y0:ye - y0, xs - x0:xe - x0] * val)

    def save(self, path):
        out = []
        for k in 'RGBA':
            a = np.asarray(self.ch[k].resize((W, H), Image.LANCZOS), dtype=np.float32) / 255.0
            if hasattr(self, 'tx'): a = np.maximum(a, self.tx[k])
            out.append((np.clip(a, 0, 1) * 255).astype(np.uint8))
        Image.fromarray(np.stack(out, -1)).save(path)


def rrect(x0, x1, y0, y1, r, k=6):
    pts = []
    for cx, cy, a0 in ((x1 - r, y0 + r, -90), (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90), (x0 + r, y0 + r, 180)):
        for i in range(k + 1):
            a = math.radians(a0 + 90.0 * i / k); pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts + [pts[0]]


def diamond(sh, cx, cy, hd=35.0):
    """Ромб WARNING (свой рисунок): белая кайма, чёрное поле, красная верхняя часть, надписи белым."""
    d = lambda k: [(cx, cy - hd * k), (cx + hd * k, cy), (cx, cy + hd * k), (cx - hd * k, cy)]
    sh.poly('A', d(1.0)); sh.poly('A', d(0.90), 0)                          # белая кайма
    sh.poly('R', d(0.90))                                                   # чёрное поле
    hi = hd * 0.90; cut = cy - 1.0; t = cut - (cy - hi)                    # рёбра ромба идут под 45°: полуширина на глубине t от вершины равна t
    top = [(cx, cy - hi), (cx + t, cut), (cx - t, cut)]
    sh.poly('B', top); sh.poly('R', top, 0)                                 # красная верхняя часть вместо чёрной
    sh.text('A', 'WARNING', cx, cy - 8.0, 5.2, 30.0, 0.8)
    sh.text('A', '15 FEET', cx, cy + 14.0, 6.5, 26.0, 0.8)
    sh.line('A', [(cx - 14, cy + 5), (cx + 14, cy + 5)], 0.8, 200)


