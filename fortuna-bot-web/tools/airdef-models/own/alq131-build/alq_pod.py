# alq_pod.py — геометрия контейнера AN/ALQ-131(V) «глубокий» (станция помех запада ecm_w) для build.py. Метры; нос +Y, верх (проушины под пилон) +Z, борта ±X.
# Все размеры снимались в ПИКСЕЛЯХ чертежа 1 (1_профиль_ALQ-131V-12_чертёж.webp, 2000 × 952, нос слева, x вправо, y вниз): _измерения/измерения_профиль.txt и сетки рядом.
# Перевод в метры — mk.S (длина 1720 пикс. = 2,40 м, как у прежней модели ELTA 8222). Начало: x = X0 (середина длины), y = YC (середина высоты от кончиков проушин до низа обтекателя).
# Ширина (±X) на чертеже сбоку не видна: HW — по видам в 3/4 (6 — рендер, 8 и 9 — Eduard, 2 — фото) — оценка, не измерение.
import math
import bpy
from mathutils import Vector
import modelkit as mk
from modelkit import B

LEN_M = 2.40                              # длина, м: как у прежней модели (2,402 м), допуск ±3 %
X_NOSE, X_TAIL = 151.0, 1871.0            # нос и хвост на чертеже 1, пикс. (силуэт x 151…1870)
DRAW_LEN = X_TAIL - X_NOSE                # 1720 пикс.
X0 = (X_NOSE + X_TAIL) / 2.0              # 1011 — середина длины
YC = 582.5                                # y чертежа на уровне z = 0: середина между кончиками проушин (371) и низом брюшного обтекателя (794)
HW = 107.0                                # полуширина коробки, пикс. (0,30 м целиком) — оценка по видам в 3/4
G_BODY, G_CONE, G_METAL, G_DARK = 0, 1, 2, 3
NS = 36                                   # точек в сечении корпуса (низ — точка 0, бока — 9 и 27, верх — 18)


def P(x, y, lat=0.0):
    """Точка по чертежу: x, y — пиксели чертежа (y вниз), lat — вбок в пикселях (+ к борту +X)."""
    return Vector((lat * mk.S, mk.Y(x), (mk.YC - y) * mk.S))


def sect(x, yt, yb, hw, nt=10.0, nb=4.0, ym=None, n=NS, cx=0.0):
    """Сечение-суперэллипс в плоскости x чертежа: верх yt, низ yb (y вниз), полуширина hw, «экватор» (самое широкое место) на ym; nt / nb — показатели
    верхней и нижней половин (2 — круг/эллипс, больше — прямее бока и острее углы). Точка 0 — самый низ, дальше против часовой, если смотреть с носа."""
    ym = (yt + yb) / 2.0 if ym is None else ym
    ring = []
    for k in range(n):
        th = -math.pi / 2 + 2 * math.pi * k / n
        c, s = math.cos(th), math.sin(th)
        e = nt if s >= 0 else nb
        lat = cx + hw * math.copysign(abs(c) ** (2.0 / e), c)
        y = ym - (ym - yt) * abs(s) ** (2.0 / e) if s >= 0 else ym + (yb - ym) * abs(s) ** (2.0 / e)
        ring.append(P(x, y, lat))
    return ring


class Stations:
    """Станции корпуса: сечение (x, yt, yb, hw, nt, nb, ym), материал полосы до следующей станции и признак «плоская стенка» (полоса за станцией — грани без сглаживания)."""
    def __init__(self): self.s = []
    def add(self, x, yt, yb, hw, nt=10.0, nb=4.0, ym=None, mat=G_BODY, flat=False): self.s.append(dict(x=x, yt=yt, yb=yb, hw=hw, nt=nt, nb=nb, ym=ym, mat=mat, flat=flat))
    def circ(self, x, R, cy, mat=G_BODY, flat=False): self.add(x, cy - R, cy + R, R, 2.0, 2.0, cy, mat, flat)


def hull_stations(stage):
    """Корпус одним рядом колец: носовой обтекатель, кольцо, хомут, шея и подбородок, коробка, переход к хвосту, хвостовая гондола.
    Этапы: 1 — только коробка (x 510…1632), 2 — плюс нос (от острия до шеи), 3 — плюс хвост."""
    st = Stations()
    if stage >= 2:
        # носовой обтекатель (тёмный): оживало по измеренным полувысотам и сдвигу оси (острие чуть выше оси кольца)
        for x, R, cy in ((151.5, 2.5, 501.0), (159, 18, 503.0), (167, 29.5, 504.5), (183, 45, 508.0), (199, 56.5, 510.5), (215, 65, 512.0),
                         (231, 71.5, 513.5), (247, 75, 514.0), (263, 76.5, 514.5), (287, 78.5, 514.5)):
            st.circ(x, R, cy, G_CONE)
        st.circ(300, 78.5, 514.5, G_BODY)        # стык обтекателя и кольца (по чертежу — вертикальный шов на x = 300)
        st.circ(407, 78.5, 514.5, G_METAL)       # хомут-кольцо (светлее): x 407…437
        st.circ(437, 78.5, 514.5, G_BODY, flat=True)
        st.circ(438.5, 84.0, 514.0, G_BODY)      # шея: радиус 84 (верх 430, низ 598), ступенька 5,5 пикс. над кольцом
        # подбородок: низ идёт под 45° от низа шеи (438, 598) к дну коробки (≈ 563, 724); верх шеи 430, затем «капот» до стенки коробки на x = 510
        st.add(455, 430, 614, 92, 2.3, 2.5, 535)
        st.add(475, 430, 633, 100, 2.6, 2.9, 565)
        st.add(500, 433, 659, 106, 3.5, 3.4, 600)
        st.add(508, 436, 667, 107, 4.0, 3.5, 615, flat=True)
    # коробка: верх y = 408, дно y ≈ 726 (на чертеже 724…727); бока ровные от верха до ≈ y 640, ниже — скругление дна (экватор на ym = 640)
    st.add(510, 408, 669, HW, 8.0, 3.5, 640)     # передняя стенка коробки над шеей (верх прыгает с 436 на 408)
    st.add(540, 408, 701, HW, 10.0, 3.8, 640)
    st.add(562, 408, 722.5, HW, 11.0, 4.0, 640)
    st.add(575, 408, 726, HW, 11.0, 4.0, 640)
    st.add(1620, 408, 726, HW, 11.0, 4.0, 640)
    st.add(1632, 408, 718, HW, 11.0, 4.0, 640, flat=(stage >= 3))   # задний торец коробки (угол внизу скруглён)
    if stage >= 3:
        st.add(1634, 409, 660, HW, 11.0, 4.0, 640)          # торец: низ прыгает с 726 на 660 (под ним — переход к гондоле)
        st.add(1647, 410, 659, HW - 1, 9.0, 4.0, 630)
        st.add(1685, 425, 659, 104, 6.0, 4.0, 620)
        st.add(1732, 444, 641, 92, 3.5, 3.0, 585)
        st.add(1782, 464, 620, 78, 2.0, 2.0, 542)           # гондола: круг радиуса 78 на оси y = 542
        st.circ(1858, 78, 542)
        st.circ(1866, 74, 542)
        st.circ(1871, 64, 542)
    return st.s


def hull(stage=9):
    """Корпус: одно тело из колец; концы закрыты плоскими крышками."""
    stn = hull_stations(stage)
    rings = [sect(s['x'], s['yt'], s['yb'], s['hw'], s['nt'], s['nb'], s['ym']) for s in stn]
    b = B(); b.loft(rings, [s['mat'] for s in stn][:-1], cap0=stn[0]['mat'], cap1=stn[-1]['mat'])
    ob = b.finish('ALQ_hull')
    for i, s in enumerate(stn[:-1]):                                  # стенки-ступени (торцы коробки, ступенька шеи): плоское затенение, без «рваных» бликов от сглаживания по тонким граням
        if s['flat']:
            for j in range(NS): ob.data.polygons[i * NS + j].use_smooth = False
    return ob


def belly():
    """Нижний (брюшной) обтекатель «deep»: трапеция сбоку (x 905…1233 у дна коробки, плоское дно y = 794 на x 972…1168), ширина ≈ 0,54 коробки."""
    rows = ((903, 722), (908, 729), (925, 752), (945, 780), (958, 791), (972, 794), (1168, 794), (1182, 790), (1196, 772), (1214, 746), (1228, 727), (1234, 722))
    hw = 58.0
    b = B()
    b.loft([sect(x, 700.0, yb, hw, 4.0, 3.2, n=18) for x, yb in rows], G_BODY, cap0=G_BODY, cap1=G_BODY)
    return b.finish('ALQ_belly')


# ───────────── мелкие детали (пиксели чертежа: x вдоль, y вниз, lat вбок) ─────────────
def box(b, x0, x1, y0, y1, l0, l1, mat):
    """Параллелепипед: x0…x1 вдоль оси, y0 (верх) … y1 (низ) на чертеже, l0…l1 вбок."""
    ring = lambda x: [P(x, y0, l0), P(x, y0, l1), P(x, y1, l1), P(x, y1, l0)]
    b.loft([ring(x0), ring(x1)], mat, cap0=mat, cap1=mat)


def extrude_xy(b, poly, l0, l1, mat):
    """Многоугольник в плоскости чертежа [(x, y)], вытянутый вбок от l0 до l1."""
    b.loft([[P(x, y, l0) for x, y in poly], [P(x, y, l1) for x, y in poly]], mat, cap0=mat, cap1=mat)


def post(b, x, lat, y_base, y_top, r, n, mat):
    """Вертикальный столбик (гайка, разъём): многоугольник радиуса r в плоскости (x, lat) от y_base вверх до y_top."""
    ring = lambda y: [P(x + r * math.cos(2 * math.pi * k / n), y, lat + r * math.sin(2 * math.pi * k / n)) for k in range(n)]
    b.loft([ring(y_base), ring(y_top)], mat, cap0=mat, cap1=mat)


def rrect_pts(x0, x1, y0, y1, r, k=3):
    """Контур прямоугольника x0…x1, y0…y1 со скруглёнными углами радиуса r (k отрезков на угол), пиксели чертежа."""
    pts = []
    for cx, cy, a0 in ((x1 - r, y0 + r, -90), (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90), (x0 + r, y0 + r, 180)):
        for i in range(k + 1):
            a = math.radians(a0 + 90.0 * i / k); pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


LUG = [(875, 403), (912, 403), (900, 388), (901, 376), (903, 374), (902, 371), (884, 371), (883, 374), (885, 376), (886, 388)]    # проушина 1 в плоскости чертежа (тело, перемычка, головка)
HOOKS = (893.0, 1357.0)                                                                                                         # x осей проушин (чертёж: 893 и 1357)
LIDS = ((925.0, 1047.0), (1203.0, 1328.0))                                                                                      # крышки на верху: x от…до, верх y = 401, низ y = 437


def top_fittings():
    """Верх коробки: две крышки-«сёдла», две проушины под пилон на подкладках с гайками, блок разъёма с двумя цилиндрами."""
    b = B()
    for x0, x1 in LIDS:                                              # крышки: верх на 7 пикс. выше верха коробки (401), на бока вниз до y = 437, на 4 пикс. шире коробки
        b.loft([sect(x0, 401.0, 437.0, HW + 4, 8.0, 8.0, n=16), sect(x1, 401.0, 437.0, HW + 4, 8.0, 8.0, n=16)], G_BODY, cap0=G_BODY, cap1=G_BODY)
    for xh in HOOKS:
        box(b, xh - 50, xh + 32, 402.5, 410.0, -20, 20, G_BODY)      # подкладка проушины
        extrude_xy(b, [(x - 893.0 + xh, y) for x, y in LUG], -8, 8, G_METAL)
        for dx in (-28, 0, 29):
            for lat in (-15, 15): post(b, xh + dx, lat, 404.0, 398.5, 6.5, 6, G_DARK)    # гайки по бокам подкладки
    for xs in (965, 1017, 1068, 1235, 1265, 1295):                    # гайки на крышках (шаг по чертежу ≈ 51 пикс. на первой крышке)
        post(b, xs, 0, 402.0, 397.0, 7.0, 6, G_DARK)
    box(b, 757, 833, 391.0, 409.0, -26, 26, G_DARK)                  # блок разъёма (чёрный)
    post(b, 784, 0, 392.0, 381.0, 9.0, 10, G_METAL)                  # малый разъём
    post(b, 815, 0, 392.0, 378.0, 12.0, 12, G_METAL)                 # большой разъём
    return b.finish('ALQ_top')


def pin():
    """Малый подвесной штырь под носовым кольцом: площадка, колонка и блок (чертёж: площадка x 320…392 под кольцом, колонка 348…380, блок 353…377 до y = 648)."""
    b = B()
    box(b, 320, 392, 590.0, 601.0, -24, 24, G_METAL)
    box(b, 348, 380, 600.0, 623.0, -13, 13, G_METAL)
    box(b, 353, 377, 622.0, 648.0, -11, 11, G_DARK)
    return b.finish('ALQ_pin')


PANELS = ((551.0, 1254.0), (1260.0, 1640.0))                         # боковые панели: x от…до, y 447…633 (чертёж: вертикальный шов на x = 1257)


def panels():
    """Боковые съёмные панели на обоих бортах — тонкие накладки (+3 пикс.) со скруглёнными углами; щель между ними (x 1254…1260) — шов."""
    b = B()
    for x0, x1 in PANELS:
        poly = rrect_pts(x0, x1, 447.0, 633.0, 9.0, 3)
        for sg in (-1, 1):
            b.loft([[P(x, y, sg * (HW - 2)) for x, y in poly], [P(x, y, sg * (HW + 3)) for x, y in poly]], G_BODY, cap0=G_BODY, cap1=G_BODY)
    return b.finish('ALQ_panels')


def pod(stage=9):
    """Строит контейнер в текущую коллекцию (после mk.configure и mk.set_materials). Этапы: 1 — коробка, 2 — нос, 3 — хвост, 4 — брюхо, крюки, разъём, панели, штырь."""
    out = [hull(stage)]
    if stage >= 4: out += [belly(), top_fittings(), panels(), pin()]
    return out
