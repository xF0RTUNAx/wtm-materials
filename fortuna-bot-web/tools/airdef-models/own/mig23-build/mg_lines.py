# консоль при 16°: шарнир (9.55, 1.70); передняя кромка и задняя - как в mg_geo (w_le, w_te), здесь только линии лонжеронов и нервюр
PIV = (9.55, 1.70)
def w_le(s): return -0.59 + s * math.tan(math.radians(16.0))
def w_te(s): return 1.93 + (1.90 - 1.93) * s / 5.29
def wing_lines():
    out = []
    for f in (0.14, 0.62):
        out.append([(PIV[0] + w_le(s) + f * (w_te(s) - w_le(s)), PIV[1] + s) for s in (0.4, 1.5, 2.6, 3.7, 4.9)])
    for s in (0.9, 1.5, 2.1, 2.7, 3.3, 3.9, 4.5):
        out.append([(PIV[0] + w_le(s) + 0.14 * (w_te(s) - w_le(s)), PIV[1] + s), (PIV[0] + w_le(s) + 0.62 * (w_te(s) - w_le(s)), PIV[1] + s)])
    return out
WING_LINES = wing_lines()
