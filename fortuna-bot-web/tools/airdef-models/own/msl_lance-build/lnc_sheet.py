# lnc_sheet.py — листы трафаретов для запекания (bake.py): lnc_decals_L.png (левый борт, нос слева) и lnc_decals_R.png (правый борт, нос справа). Положения — с картинок Mark: надпись «U.S. ARMY» (картинки 3 и 4),
# метки-«чёрточки» у мест ремней (картинка 1) и два жёлто-песочных прямоугольника у стыка головной части (картинка 1). Единицы листа — сантиметры вдоль оси (x вправо к хвосту, начало — середина длины) и по высоте (y вниз).
# Каналы PNG (RGBA, без цвета: это маски): R — чёрная краска, G — тонкие линии, B — жёлто-песочные заплатки, A — белая краска. Шрифт и рисовалка — из ../ALQ-131/alq_sheet.py (растровый 5×7).
# Запуск: /usr/bin/python3 -I lnc_sheet.py "<папка модели>"
import sys, os, math
sys.dont_write_bytecode = True
sys.path.insert(0, '/Users/mark./Downloads/Воздушное превосходство/Модели/Свои/ALQ-131')
import alq_sheet as A

A.X0 = 0.0
A.X_MIN, A.X_MAX, A.Y_MIN, A.Y_MAX = -330, 330, -34, 34       # см вдоль оси и по высоте
A.K = 4                                                         # пикселей листа на см
A.W, A.H = (A.X_MAX - A.X_MIN) * A.K, (A.Y_MAX - A.Y_MIN) * A.K


def draw(sh):
    # «U.S. ARMY»: по картинке 4 текст 0,8 м × 0,115 м, середина ≈ 0,31 м позади середины длины, чуть выше оси
    sh.text('A', 'U.S. ARMY', 31.0, -3.0, 11.5, 80.0, 1.0, 0.92, block=31.0)
    # пары белых чёрточек у мест ремней (картинка 1): поперёк корпуса, высотой 14 см
    for xc in (145.0, -62.0):
        for dx in (-2.5, 2.5): sh.line('A', [(xc + dx, -7.0), (xc + dx, 7.0)], 1.2, 235)
    # жёлто-песочные заплатки 11 × 7,5 см на расстоянии 1,6 и 2,57 м от носика (картинка 1)
    for xc in (-149.0, -52.0): sh.poly('B', [(xc - 5.5, -13.75), (xc + 5.5, -13.75), (xc + 5.5, -6.25), (xc - 5.5, -6.25)])


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    os.makedirs(os.path.join(out, '_текстуры'), exist_ok=True)
    for side, mirror in (('L', False), ('R', True)):
        sh = A.Sheet(mirror); draw(sh); p = os.path.join(out, '_текстуры', f'lnc_decals_{side}.png'); sh.save(p); print('лист', p, (A.W, A.H))
