def cage(turn):
    b = B('pod'); c = CG; L = c['y1'] - c['y0']; t = 0.035; zm = (c['z0'] + c['z1']) / 2; hz = c['z1'] - c['z0']
    ych = 0.32                                                               # скос нижней передней кромки борта (фото 08)
    for s in (-1, 1):
        x = s * c['x']
        prof = [(c['y0'], c['z0']), (c['y1'] - ych, c['z0']), (c['y1'], c['z0'] + ych), (c['y1'], c['z1']), (c['y0'], c['z1'])]
        b.loft([[V(x - s * t, y, z) for y, z in prof], [V(x, y, z) for y, z in prof]], M_BODY)                     # борт
        # двери-панели (три больших, фото 08): накладки 8 мм, петли сверху, замки снизу
        for ya, yb in ((c['y0'] + 0.15, c['y0'] + 1.75), (c['y0'] + 1.85, c['y0'] + 3.45), (c['y0'] + 3.55, c['y1'] - ych - 0.10)):
            b.box((x + s * 0.004, (ya + yb) / 2, zm), (0.008, yb - ya, hz - 0.18), M_BODY)
            for yy in (ya + 0.25, yb - 0.25): b.box((x + s * 0.012, yy, c['z1'] - 0.10), (0.016, 0.16, 0.035), M_STEEL)
            for yy in (ya + 0.30, yb - 0.30): b.box((x + s * 0.013, yy, c['z0'] + 0.11), (0.018, 0.08, 0.05), M_DARK)
        for yy in (c['y0'] + 1.80, c['y0'] + 3.50):                                                             # стойки между дверями
            b.box((x + s * 0.012, yy, zm), (0.024, 0.08, hz - 0.02), M_BODY)
        for zz in (c['z0'] + 0.03, c['z1'] - 0.03):                                                              # пояса
            b.box((x + s * 0.02, (c['y0'] + (c['y1'] - (ych if zz < zm else 0))) / 2, zz), (0.04, L - (ych if zz < zm else 0), 0.06), M_BODY)
        b.box((s * (c['x'] - 0.07), (c['y0'] + c['y1']) / 2, c['z1'] + 0.02), (0.08, L, 0.04), M_STEEL)                      # рельс стрелы
        b.box((x + s * 0.010, c['y0'] + 0.60, c['z1'] - 0.12), (0.006, 0.30, 0.05), M_WHITE)                                   # табличка
        for yy in (c['y0'] + 0.10, c['y1'] - 0.10):                                                              # рым-болты на верхних углах
            lathe(b, V(x - s * 0.06, yy, c['z1'] + 0.005), V(0, 0, 1), [(0, 0.04), (0.03, 0.035), (0.05, 0.02), (0.06, 0.001)], M_STEEL, n=8)
    b.box((0, (c['y0'] + c['y1']) / 2, c['z1'] - t / 2), (2 * c['x'], L, t), M_BODY)                                         # крыша
    for k in range(8): b.box((0, c['y0'] + 0.40 + k * 0.66, c['z1'] + 0.006), (2 * c['x'] - 0.30, 0.05, 0.012), M_BODY)     # рёбра крыши
    # днище открыто (фото 07): поперечины и продольные балки, торцевые рамы
    for k in range(9):
        yy = c['y0'] + 0.12 + k * (L - ych - 0.24) / 8
        b.box((0, yy, c['z0'] + 0.04), (2 * c['x'] - 0.04, 0.07, 0.08), M_BODY)
    for xx in (-0.45, 0.45): b.box((xx, (c['y0'] + c['y1'] - ych) / 2, c['z0'] + 0.04), (0.06, L - ych, 0.08), M_BODY)
    for yy, d in ((c['y1'], 1), (c['y0'], -1)):                              # торцевые рамы: коробчатые, с угловыми накладками
        zb = c['z0'] + (ych if d > 0 else 0)
        for zz in (zb + 0.06, c['z1'] - 0.06): b.box((0, yy - d * 0.06, zz), (2 * c['x'] + 0.04, 0.12, 0.12), M_BODY)
        for s in (-1, 1):
            b.box((s * (c['x'] - 0.04), yy - d * 0.06, (zb + c['z1']) / 2), (0.12, 0.12, c['z1'] - zb), M_BODY)
            for zz in (zb + 0.06, c['z1'] - 0.06): b.box((s * (c['x'] + 0.01), yy - d * 0.06, zz), (0.04, 0.14, 0.14), M_STEEL)
    b.loft([[V(-c['x'], c['y1'] - ych, c['z0']), V(c['x'], c['y1'] - ych, c['z0'])], [V(-c['x'], c['y1'], c['z0'] + ych), V(c['x'], c['y1'], c['z0'] + ych)]], M_BODY, cap0=False, cap1=False, closed=False)
    # люлька под днищем: коробчатые балки, поперечины, проушины петли и цилиндров
    for s in (-1, 1):
        b.box((s * 0.30, (c['y0'] + c['y1']) / 2 + 0.3, c['z0'] - 0.035), (0.10, L - 1.2, 0.07), M_BODY)
        xl = s * 0.915                                                       # проушина петли: на борту снаружи, вниз до оси
        b.loft([[V(xl - 0.025, H.y - 0.25, c['z0'] + 0.30), V(xl - 0.025, H.y + 0.35, c['z0'] + 0.30), V(xl - 0.025, H.y + 0.08, H.z - 0.08), V(xl - 0.025, H.y - 0.08, H.z - 0.08)],
                [V(xl + 0.025, H.y - 0.25, c['z0'] + 0.30), V(xl + 0.025, H.y + 0.35, c['z0'] + 0.30), V(xl + 0.025, H.y + 0.08, H.z - 0.08), V(xl + 0.025, H.y - 0.08, H.z - 0.08)]], M_BODY)
        lathe(b, V(s * 0.89, H.y, H.z), V(s, 0, 0), [(0, 0.08), (0.04, 0.08), (0.04, 0.05), (0.048, 0.05), (0.048, 0.001)], M_STEEL, n=14)
        p = P_CYL[(s + 1) // 2]
        for dx in (-0.075, 0.075): b.box((p.x + dx, p.y, (c['z0'] + p.z - 0.05) / 2), (0.022, 0.16, c['z0'] - p.z + 0.05), M_BODY)
    for yy in (P_CYL[0].y - 0.12, P_CYL[0].y + 0.12): b.box((0, yy, c['z0'] - 0.035), (0.70, 0.06, 0.07), M_BODY)
    return mk(b, pivot=H, parent=turn)


def boom(pod):
    """рама-стрела перезарядки (фото 07): квадратные балки по верхним кромкам клетки выходят за дульный торец, на концах - замки, над ними П-рама"""
    b = B('boom'); c = CG; xa = c['x'] - 0.07; zt = c['z1'] + 0.12; y1 = c['y1']; ye = y1 + 0.30; hp = 0.32
    for s in (-1, 1):
        x = s * xa
        b.box((x, (c['y0'] + 1.0 + ye) / 2, zt), (0.13, ye - c['y0'] - 1.0, 0.13), M_BODY)                                   # балка
        for yy in (c['y0'] + 1.15, y1 - 0.45): b.box((x, yy, zt - 0.075), (0.16, 0.26, 0.03), M_STEEL)                        # ползуны
        b.box((x, ye + 0.05, zt - 0.02), (0.18, 0.18, 0.20), M_BODY)                                                         # концевой блок
        b.box((x, ye + 0.145, zt - 0.06), (0.16, 0.02, 0.08), M_YELLOW)                                                      # замок захвата (фото 07: жёлтый)
        b.box((x, ye + 0.05, zt - 0.14), (0.10, 0.10, 0.05), M_YELLOW)
        b.beam([V(x, ye + 0.05, zt + 0.08), V(x, ye + 0.02, zt + hp), V(x * 0.97, ye - 0.04, zt + hp + 0.12)], V(1, 0, 0), 0.13, 0.13, M_BODY)   # стойка П-рамы
        b.bar(V(x, ye - 0.30, zt + 0.065), V(x, ye - 0.02, zt + hp - 0.04), 0.06, 0.05, M_BODY)                               # подкос
    b.bar(V(-xa * 0.97 - 0.06, ye - 0.04, zt + hp + 0.12), V(xa * 0.97 + 0.06, ye - 0.04, zt + hp + 0.12), 0.14, 0.13, M_BODY)   # поперечина
    b.box((0, ye - 0.04, zt + hp + 0.03), (0.24, 0.14, 0.10), M_DARK)            # лебёдка, трос, крюк
    b.cyl(V(0, ye - 0.04, zt + hp - 0.02), V(0, ye - 0.04, zt + 0.12), 0.012, 0.012, M_STEEL, n=6)
    b.box((0, ye - 0.04, zt + 0.10), (0.08, 0.05, 0.06), M_DARK)
    b.cyl(V(-0.06, ye - 0.04, zt + hp + 0.21), V(0.06, ye - 0.04, zt + hp + 0.21), 0.03, 0.03, M_WHITE, n=8)   # метка-фонарь на поперечине (фото 07)
    return mk(b, pivot=H, parent=pod)


def container(pod, var):
    """съёмный контейнер: каркас с угловыми фитингами, торцевые плиты, трубы с ободами; крышки и пустышки дульных срезов - отдельно"""
    c = CT; nm = 'pod_' + var; b = B(nm); L = c['y1'] - c['y0']; zm = (c['z0'] + c['z1']) / 2
    for s in (-1, 1):
        for zz in (c['z0'] + 0.035, c['z1'] - 0.035): b.box((s * (c['x'] - 0.035), (c['y0'] + c['y1']) / 2, zz), (0.07, L, 0.07), M_BODY)
    for yy in (c['y0'] + 0.04, c['y1'] - 0.04):
        for zz in (c['z0'] + 0.035, c['z1'] - 0.035): b.box((0, yy, zz), (2 * c['x'], 0.08, 0.07), M_BODY)
        for s in (-1, 1):
            b.box((s * (c['x'] - 0.035), yy, zm), (0.07, 0.08, c['z1'] - c['z0']), M_BODY)
            for zz in (c['z0'] + 0.05, c['z1'] - 0.05): b.box((s * (c['x'] - 0.045), yy, zz), (0.10, 0.10, 0.10), M_STEEL)   # угловые фитинги
    tubes = []
