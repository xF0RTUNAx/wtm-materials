def grate(b, x, y0, y1, z0, z1, s):
    """решётчатый борт (перфорированный лист в рамке, фото 08): тёмный лист, рамка и стойки; дырки - в текстуре"""
    b.box((x, (y0 + y1) / 2, (z0 + z1) / 2), (0.012, y1 - y0, z1 - z0), M_DARK)
    for zz in (z0 + 0.015, z1 - 0.015): b.box((x + s * 0.01, (y0 + y1) / 2, zz), (0.02, y1 - y0, 0.03), M_BODY)
    n = max(2, int((y1 - y0) / 0.55))
    for k in range(n + 1): b.box((x + s * 0.01, y0 + (y1 - y0) * k / n, (z0 + z1) / 2), (0.02, 0.035, z1 - z0), M_BODY)


def base():
    b = B('body_base')
    y0, y1 = -3.40, 0.55
    b.loft([[V(-0.98, y0, BASE_Z0), V(0.98, y0, BASE_Z0), V(0.98, y1, BASE_Z0), V(-0.98, y1, BASE_Z0)],
            [V(-0.98, y0, BASE_Z1 - 0.05), V(0.98, y0, BASE_Z1 - 0.05), V(0.98, y1, BASE_Z1 - 0.05), V(-0.98, y1, BASE_Z1 - 0.05)],
            [V(-0.94, y0 + 0.04, BASE_Z1), V(0.94, y0 + 0.04, BASE_Z1), V(0.94, y1 - 0.04, BASE_Z1), V(-0.94, y1 - 0.04, BASE_Z1)]], M_BODY)
    for s in (-1, 1):                                                        # решётчатые борта-подножки и кронштейны
        grate(b, s * 1.07, -3.30, 0.45, BASE_Z0 - 0.02, BASE_Z1 - 0.02, s)
        for yy in (-3.0, -2.0, -1.0, 0.0):
            b.loft([[V(s * 0.98, yy - 0.04, BASE_Z0), V(s * 0.98, yy + 0.04, BASE_Z0), V(s * 0.98, yy + 0.04, BASE_Z1 - 0.06), V(s * 0.98, yy - 0.04, BASE_Z1 - 0.06)],
                    [V(s * 1.06, yy - 0.04, BASE_Z1 - 0.10), V(s * 1.06, yy + 0.04, BASE_Z1 - 0.10), V(s * 1.06, yy + 0.04, BASE_Z1 - 0.06), V(s * 1.06, yy - 0.04, BASE_Z1 - 0.06)]], M_BODY)
    for k in range(5): b.box((0, -3.0 + 0.85 * k, BASE_Z1 + 0.004), (1.70, 0.04, 0.008), M_DARK)            # швы настила
    # погон: неподвижное кольцо с зубьями и болтами
    lathe(b, V(T.x, T.y, BASE_Z1 - 0.01), V(0, 0, 1), [(0, TURN_R + 0.06), (T.z - BASE_Z1 - 0.015, TURN_R + 0.06), (T.z - BASE_Z1 - 0.015, TURN_R + 0.005)], M_DARK, n=64, cap0=True, cap1=False)   # кольцо погона снаружи платформы
    for k in range(24):
        a = 2 * math.pi * (k + 0.5) / 24; p = V(T.x + math.cos(a) * (TURN_R + 0.035), T.y + math.sin(a) * (TURN_R + 0.035), T.z - 0.03)
        b.cyl(p - V(0, 0, 0.004), p + V(0, 0, 0.012), 0.014, 0.012, M_STEEL, n=6)
    b.box((0.55, 0.30, BASE_Z1 + 0.006), (0.60, 0.40, 0.012), M_DARK)         # лючки гидроблока на настиле (ниже платформы)
    b.box((-0.50, 0.30, BASE_Z1 + 0.006), (0.50, 0.40, 0.012), M_DARK)
    # стойка-упор клетки у кормы (фото 09) - ниже клетки в походном; лестница
    ladder(b, V(-1.10, -3.36, 0.30), V(-1.10, -3.36, BASE_Z1 - 0.02), w=0.32, rungs=3, mat=M_DARK)
    # шланги вдоль основания
    for k, xx in enumerate((0.70, 0.76, 0.82)):
        tube_path(b, [V(xx, 0.40, BASE_Z1 + 0.017), V(xx, -0.40, BASE_Z1 + 0.017), V(xx - 0.05 * k, -0.80, BASE_Z1 + 0.017)], 0.015, M_BLACK, n=6)
    return mk(b)


def turn_part():
    b = B('turn'); zt = PLAT_TOP
    lathe(b, T, V(0, 0, 1), [(0, 0.001), (0, TURN_R - 0.08), (0.02, TURN_R - 0.08), (0.02, TURN_R), (zt - T.z - 0.02, TURN_R), (zt - T.z, TURN_R - 0.03), (zt - T.z, 0.001)], M_BODY, n=64)
    for k in range(72):                                                      # зубья венца
        a = 2 * math.pi * k / 72; d = V(math.cos(a), math.sin(a), 0); t = V(-d.y, d.x, 0)
        p = T + d * (TURN_R - 0.075) + V(0, 0, 0.01)
        b.loft([[p - t * 0.02 - d * 0.0, p + t * 0.02, p + t * 0.02 + V(0, 0, 0.02), p - t * 0.02 + V(0, 0, 0.02)],
                [p - t * 0.01 - d * 0.03, p + t * 0.01 - d * 0.03, p + t * 0.01 - d * 0.03 + V(0, 0, 0.02), p - t * 0.01 - d * 0.03 + V(0, 0, 0.02)]], M_STEEL)
    for k in range(20):                                                      # болты по кругу
        a = 2 * math.pi * k / 20; p = T + V(math.cos(a) * (TURN_R - 0.12), math.sin(a) * (TURN_R - 0.12), zt - T.z)
        b.cyl(p, p + V(0, 0, 0.018), 0.018, 0.015, M_STEEL, n=6)
    for k in range(12):                                                      # рёбра платформы (ниже балок люльки)
        a = 2 * math.pi * k / 12; d = V(math.cos(a), math.sin(a), 0)
        if abs(d.x) > 0.75 or d.y > 0.5: b.bar(T + d * 0.30 + V(0, 0, zt - T.z + 0.02), T + d * (TURN_R - 0.16) + V(0, 0, zt - T.z + 0.02), 0.05, 0.04, M_BODY)
    for s in (-1, 1):                                                        # хвост платформы до петли: коробчатые балки с облегчающими окнами
        x = s * 0.99; ya, yb = T.y - 0.75, H.y - 0.15
        b.box((x, (ya + yb) / 2, (T.z + zt) / 2), (0.12, ya - yb, zt - T.z), M_BODY)
        for k in range(3):
            b.box((x + s * 0.061, ya - 0.35 - k * 0.42, (T.z + zt) / 2), (0.004, 0.22, 0.06), M_DARK)
    b.box((0, H.y - 0.12, (T.z + zt) / 2), (2.10, 0.12, zt - T.z), M_BODY)
    for yy in (T.y - 1.05, H.y + 0.25): b.box((0, yy, (T.z + zt) / 2 - 0.01), (1.90, 0.08, zt - T.z - 0.02), M_BODY)
    for s in (-1, 1):                                                        # щёки петли - снаружи бортов клетки (клетка при подъёме проходит между ними)
        x = s * 0.99
        b.loft([[V(x - 0.04, H.y - 0.20, zt), V(x - 0.04, H.y + 0.42, zt), V(x - 0.04, H.y + 0.10, H.z + 0.07), V(x - 0.04, H.y - 0.10, H.z + 0.07)],
                [V(x + 0.04, H.y - 0.20, zt), V(x + 0.04, H.y + 0.42, zt), V(x + 0.04, H.y + 0.10, H.z + 0.07), V(x + 0.04, H.y - 0.10, H.z + 0.07)]], M_BODY)
        lathe(b, V(x + s * 0.035, H.y, H.z), V(s, 0, 0), [(0, 0.09), (0.02, 0.09), (0.02, 0.055), (0.035, 0.055), (0.035, 0.001)], M_STEEL, n=14)
        b.loft([[V(x + s * 0.04, H.y + 0.40, zt), V(x + s * 0.04, H.y + 0.10, H.z + 0.06)], [V(x + s * 0.12, H.y + 0.55, zt), V(x + s * 0.12, H.y + 0.35, zt + 0.02)]], M_BODY, cap0=False, cap1=False, closed=False)   # косынка снаружи щеки
        a = A_CYL[(s + 1) // 2]                                              # опоры цилиндров
        for dx in (-0.10, 0.10): b.box((a.x + dx, a.y, (zt + a.z + 0.05) / 2), (0.03, 0.16, a.z + 0.05 - zt), M_BODY)
        b.cyl(a + V(-0.12, 0, 0), a + V(0.12, 0, 0), 0.035, 0.035, M_STEEL, n=8)
    b.box((0, T.y + 0.55, zt + 0.045), (0.46, 0.30, 0.09), M_BODY)            # блок гидравлики на платформе (ниже балок люльки)
    b.box((0, T.y + 0.55, zt + 0.094), (0.34, 0.20, 0.008), M_DARK)
    for k in range(3):
        tube_path(b, [V(-0.12 + 0.12 * k, T.y + 0.40, zt + 0.06), V(-0.12 + 0.12 * k, T.y + 0.10, zt + 0.03), V(-0.30 + 0.30 * k, T.y - 0.45, zt + 0.03)], 0.016, M_BLACK, n=6)
    return mk(b, pivot=T)


def cylinders(turn, pod):
    out = []
    for s, sd in ((-1, 'l'), (1, 'r')):
        a, p = A_CYL[(s + 1) // 2], P_CYL[(s + 1) // 2]
        b = B('cyl_body_' + sd)                                               # корпус: вдоль +Y от опоры A (игра наводит +Y на проушину P)
        lathe(b, a, V(0, 1, 0), [(0, 0.001), (0, 0.05), (0.03, 0.075), (0.08, 0.075), (0.09, 0.08), (CYL_BODY - 0.08, 0.08), (CYL_BODY - 0.07, 0.072), (CYL_BODY - 0.02, 0.072), (CYL_BODY, 0.06), (CYL_BODY, 0.052)], M_BODY, n=16)
        b.cyl(a + V(-0.08, 0, 0), a + V(0.08, 0, 0), 0.045, 0.045, M_STEEL, n=8)
        b.cyl(a + V(0, 0.25, 0.08), a + V(0, 0.32, 0.105), 0.018, 0.018, M_BLACK, n=6)                          # штуцер
        out.append(mk(b, pivot=a, parent=turn))
        b = B('cyl_rod_' + sd)                                                # шток (две ступени): вдоль +Y от проушины P (игра наводит +Y на опору A)
        b.cyl(p + V(-0.06, 0, 0), p + V(0.06, 0, 0), 0.045, 0.045, M_STEEL, n=10)
        lathe(b, p, V(0, 1, 0), [(0, 0.035), (0.05, 0.048), (CYL_ROD * 0.55, 0.048), (CYL_ROD * 0.55, 0.06), (CYL_ROD * 0.58, 0.06), (CYL_ROD * 0.58, 0.058), (CYL_ROD, 0.058), (CYL_ROD, 0.001)], M_STEEL, n=14)
        out.append(mk(b, pivot=p, parent=pod))
    return out


