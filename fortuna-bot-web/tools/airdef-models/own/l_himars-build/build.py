def quad(b, c, u, v, n, w, h, mat, t=0.012):
    """плоская накладка: центр c, ширина w вдоль u, высота h вдоль v, наружу n"""
    u, v, n = Vector(u).normalized(), Vector(v).normalized(), Vector(n).normalized()
    ring = lambda d: [Vector(c) + n * d + u * (sx * w / 2) + v * (sz * h / 2) for sx, sz in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
    b.loft([ring(-0.005), ring(t)], mat)


