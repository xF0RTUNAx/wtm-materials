# консоль при 16°: шарнир, передняя и задняя кромки - как в su_geo (единицы чертежа), здесь лонжероны и нервюры в метрах
PIV_DU = (13.80, 1.90); S_TIP = 6.54
def w_le(s): return -0.813 + s * math.tan(math.radians(16.0))
def w_te(s): return 1.89 + (1.86 - 1.89) * s / S_TIP
def P(s, f): return (T(PIV_DU[0] + w_le(s) + f * (w_te(s) - w_le(s))), (PIV_DU[1] + s) * SCL)
def wing_lines():
    out = []
    for f in (0.15, 0.60):
        out.append([P(s, f) for s in (1.2, 2.5, 3.8, 5.1, 6.3)])
    for s in (1.8, 2.5, 3.2, 3.9, 4.6, 5.3, 6.0):
        out.append([P(s, 0.15), P(s, 0.60)])
    return out
WING_LINES = wing_lines()
