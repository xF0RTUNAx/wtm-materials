# Х-31П — своя игровая модель по картинкам Mark (Свои/Х-31П/: чертёж-3вида.png — чертёж «изделие 77П», три вида и виды спереди/сзади;
# вид-сверху-размеры.png — рендер сверху с размерами 5340 / 1051,4 / 1271,41, нос слева, 532 × 375).
# Общие функции — ../_kit/modelkit.py (репозиторий), рецепт — README там же. Размеры ниже — в пикселях рендера вид-сверху-размеры.png:
# нос x=10, хвост x=437 (длина 427 пикс.), ось y=213,5, радиус корпуса 16,3 пикс. Чертёж-3вида обрезан по краям, поэтому длинные станции взяты с рендера,
# а компоновка (воздухозаборники и оперение крестом ×, радиусы, форма крыла в плане, лючок, проушины) — с чертежа.
# Запуск (рекомендуется — фоновый Blender, вместе с deliver.py):
#   K31_OUT="<папка модели>" /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup --python build.py --python deliver.py
#
# Список деталей (картинки → сделано):
#   ✓ носовой обтекатель с кольцевыми швами (x=67 и 100)          ✓ цилиндрический корпус со стыками отсеков
#   ✓ четыре воздухозаборника ПВРД ×, конус спереди, два пояса     ✓ перемычки от заборников к корпусу (на чертеже спереди — треугольные)
#   ✓ четыре крыла в плане со стреловидной передней кромкой       ✓ четыре рулевых пластины на хвосте
#   ✓ длинный лючок на цилиндре (чертёж сбоку, перед заборниками) ✓ два тёмных гнезда рядом с лючком
#   ✓ две проушины подвески сверху                                ✓ сопло в хвосте (тёмная чаша)
#   ✗ заклёпки и мелкие винты — слишком мелко для 6 тыс. треугольников;  ✗ окно подвесного узла в центре (рамка на чертеже) — внутреннее, не форма
import sys, importlib, math
sys.dont_write_bytecode = True
sys.path.insert(0, '/Users/mark./wtm-materials/fortuna-bot-web/tools/airdef-models/own/_kit')
import modelkit as mk; importlib.reload(mk)
from modelkit import B, Vector, circ, profile, panel, prism, trap, rrect, ell, decal, Y, PR_WING, PR_PLATE, PR_FLAP

S = 4.727 / 427.0           # метров на пиксель: длина как у прежней модели в игре (4,727 м — по glb) на 427 пикс. рендера
mk.configure('KH31P', S, x0=223.5, yc=213.5, rb=16.3, nose='left')
mk.set_materials([('K31_body', (0.50, 0.51, 0.49)), ('K31_wing', (0.40, 0.41, 0.40)),
                  ('K31_ctrl', (0.22, 0.23, 0.23)), ('K31_dark', (0.035, 0.036, 0.04))])
M_BODY, M_WING, M_CTRL, M_DARK = 0, 1, 2, 3
AZ = (45.0, 135.0, 225.0, 315.0)                           # заборники и оперение крестом ×
RS = 26.5                                                  # расстояние оси заборника от оси корпуса (с вида спереди: 1,66 R)
RSC = RS / math.sqrt(2.0)                                  # смещение центра заборника вбок и вверх

# ───────────────────────── корпус (вращение) ─────────────────────────
BASE = [
    (10.0, 1.6, M_BODY), (14.0, 4.2, M_BODY), (20.0, 6.9, M_BODY), (30.0, 10.0, M_BODY), (45.0, 12.8, M_BODY),
    (60.0, 14.8, M_BODY), (80.0, 16.0, M_BODY), (100.0, 16.3, M_BODY),                                   # носовой обтекатель
    (172.0, 16.3, M_BODY), (182.0, 14.0, M_BODY), (200.0, 13.2, M_BODY),                                 # переход к маршевой части
    (430.0, 13.2, M_BODY), (434.0, 12.4, M_BODY), (437.0, 11.4, M_DARK),                                 # хвост
    (437.0, 9.4, M_DARK), (433.0, 7.6, M_DARK), (431.0, 5.0, M_DARK),                                    # торец и чаша сопла
]
GROOVES = [(67.0, 1.0, 0.8), (100.0, 0.9, 0.8), (150.0, 0.8, 0.7), (262.0, 0.8, 0.7), (300.0, 1.0, 0.8),
           (372.0, 0.8, 0.7), (420.0, 0.8, 0.7)]                                # стыки отсеков
prof = profile(BASE, GROOVES)
b = B()
b.loft([circ(x, R) for x, R, _ in prof], [m for _, _, m in prof[:-1]], cap0=M_DARK, cap1=M_DARK)
b.finish('K31_body')

# ───────────────────────── воздухозаборники ПВРД ─────────────────────────
SC = [(172.0, 0.4), (176.0, 1.9), (182.0, 3.7), (192.0, 5.5), (205.0, 6.2), (261.0, 6.2), (261.0, 5.5), (263.0, 5.5), (263.0, 6.2),
      (339.0, 6.2), (339.0, 5.5), (341.0, 5.5), (341.0, 6.2), (412.0, 6.2), (420.0, 5.5), (427.0, 4.0), (431.0, 2.4)]
b = B()
for phi in AZ:
    sx, sz = RSC * math.cos(math.radians(phi - 45.0) + math.pi / 4.0) * math.sqrt(2.0), RSC * math.sin(math.radians(phi - 45.0) + math.pi / 4.0) * math.sqrt(2.0)
    sx, sz = RS * math.cos(math.radians(phi)), RS * math.sin(math.radians(phi))
    b.loft([circ(x, R, n=16, cx=sx, cz=sz) for x, R in SC], M_BODY, cap0=M_BODY, cap1=M_DARK)
b.finish('K31_scoops')

b = B()   # перемычки от заборников к корпусу — пластины по диагонали
for phi in AZ:
    panel(b, phi, [(10.0, 206.0, 410.0, 10.0), (17.0, 206.0, 410.0, 8.5), (26.0, 206.0, 410.0, 4.0)], PR_PLATE, M_WING)
b.finish('K31_webs')

# ───────────────────────── крылья и рули ─────────────────────────
b = B()
for phi in AZ:   # стреловидное крыло: корень на заборнике, передняя кромка отходит к концу
    panel(b, phi, [(24.0, 318.0, 398.0, 2.6), (36.0, 342.0, 398.0, 2.3), (48.0, 364.0, 398.0, 2.0)], PR_WING, M_WING)
b.finish('K31_wings')

b = B()
for phi in AZ:   # рулевые пластины за крылом
    panel(b, phi, [(14.0, 400.0, 413.0, 2.4), (36.0, 401.0, 413.0, 2.4), (54.0, 403.0, 413.0, 1.8)], PR_FLAP, M_CTRL)
b.finish('K31_ctrl')

# ───────────────────────── накладки на корпус ─────────────────────────
b = B()
for sd in (1, -1):
    decal(b, 130.0, 0.0, rrect(36.0, 6.5, 3.0), sd, 0.9, M_WING)                 # длинный лючок на цилиндре перед заборниками
b.finish('K31_hatches')

b = B()
for sd in (1, -1):
    for x in (104.0, 160.0):
        decal(b, x, -12.2, ell(2.6, 2.0, 10), sd, 0.7, M_DARK)                       # нижние гнёзда вдоль борта
b.finish('K31_slots')

# ───────────────────────── проушины подвески сверху ─────────────────────────
b = B()
for lat in (3.2, -3.2):
    pts = lambda lx: [Vector((lx * S, Y(250.0), 12.4 * S)), Vector((lx * S, Y(290.0), 12.4 * S)),
                      Vector((lx * S, Y(282.0), 19.5 * S)), Vector((lx * S, Y(258.0), 19.5 * S))]
    b.loft([pts(lat - 1.3), pts(lat + 1.3)], M_DARK, cap0=M_DARK, cap1=M_DARK)
b.finish('K31_lugs')

mk.stats()
