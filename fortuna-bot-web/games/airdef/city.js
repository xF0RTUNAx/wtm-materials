// ═════════════ Генерация ═════════════
export function buildCity(seed = 1) {
  const rnd = mulberry32((seed * 2654435761) >>> 0);
  const objects = makeObjects();
  const keepOut = objects.map((o) => ({ x0: o.x - o.w / 2 - 30, x1: o.x + o.w / 2 + 30, z0: o.z - o.d / 2 - 30, z1: o.z + o.d / 2 + 30 }));
  const blocked = (x0, x1, z0, z1) => keepOut.some((k) => x1 > k.x0 && x0 < k.x1 && z1 > k.z0 && z0 < k.z1);

  // здания — плоские массивы (на 40 тыс. коробок объекты были бы тяжелее)
  let cap = 50000, n = 0;
  const BX = new Float32Array(cap), BZ = new Float32Array(cap), BW = new Float32Array(cap), BD = new Float32Array(cap), BH = new Float32Array(cap), BY = new Float32Array(cap), BK = new Uint8Array(cap), BC = new Float32Array(cap);
  // y0 — высота основания над землёй (верхние ступени башен, шпили)
  const put = (x, z, w, d, h, k, y0 = 0) => {
    if (n >= cap) return;
    BX[n] = x; BZ[n] = z; BW[n] = w; BD[n] = d; BH[n] = h; BK[n] = k; BY[n] = y0; BC[n] = rnd(); n++;
  };
  // башня Сити: высокие — ступенями (уступы), иногда с короной и шпилем
  const tower = (x, z, w, d, H, k) => {
    if (H < 110 || rnd() < 0.35) { put(x, z, w, d, H, k); return; }
    const h1 = H * (0.45 + rnd() * 0.25), w2 = w * (0.62 + rnd() * 0.2), d2 = d * (0.62 + rnd() * 0.2);
    put(x, z, w, d, h1, k);
    if (rnd() < 0.5) { const h2 = (H - h1) * 0.6; put(x, z, w2, d2, h2, k, h1); put(x, z, w2 * 0.72, d2 * 0.72, H - h1 - h2, k, h1 + h2); }
    else put(x, z, w2, d2, H - h1, k, h1);
    if (rnd() < 0.4) put(x, z, 2.2, 2.2, 18 + rnd() * 45, KIND.PLAIN, H); // шпиль-антенна
  };
  const G = CITY.GRID, N = Math.ceil(CITY.R / G) + 1;
  const urb = new Uint8Array(RS * RS); // квартал (i, j) городской — вокруг него улицы
  const hwy = (k) => ((k % HWY_EVERY) + HWY_EVERY) % HWY_EVERY === 0;
  for (let i = -N; i < N; i++) for (let j = -N; j < N; j++) {
    const x0 = i * G + lineW(i) / 2, x1 = (i + 1) * G - lineW(i + 1) / 2, z0 = j * G + lineW(j) / 2, z1 = (j + 1) * G - lineW(j + 1) / 2;
    const cx = (x0 + x1) / 2, cz = (z0 + z1) / 2;
    if (Math.hypot(cx, cz) > CITY.HALF - 3000) continue;
    const zn = zoneAt(cx, cz), e = edgeIn(cx, cz);
    if (zn === ZONE.WATER || zn === ZONE.AIR || zn === ZONE.PARK) continue;
    if (zn === ZONE.FIELD) {
      // за городом: хутора вдоль трасс и редеющая окраина у края застройки (раньше — случайные кварталы посреди поля)
      const p = Math.max(hwy(i) || hwy(i + 1) || hwy(j) || hwy(j + 1) ? 0.22 : 0, e > -700 ? 0.5 * (1 + e / 700) : 0);
      if (rnd() >= p) continue;
    }
    const qb = (j + RN) * RS + i + RN, n0 = n;
    if (e > 350) urb[qb] = 2; // окраина и деревни (1) — ниже, только если в квартале встал хоть один дом
    // квартал у реки — набережная 40 м
    const near = Math.min(Math.abs(x0 - riverX(z0)), Math.abs(x1 - riverX(z0)), Math.abs(x0 - riverX(z1)), Math.abs(x1 - riverX(z1)), Math.abs(cx - riverX(cz)));
    if (near < CITY.RIVER_W / 2 + 45 || Math.sign(x0 - riverX(cz)) !== Math.sign(x1 - riverX(cz))) continue;
    if (blocked(x0, x1, z0, z1)) continue;
    const bw = x1 - x0, bd = z1 - z0, m = 8; // отступ от улицы
    const d = Math.hypot(cx - CX, cz - CZ);
    if (zn === ZONE.CBD) {
      const k = clamp(1.15 - d / 2300, 0.25, 1);
      const split = rnd() < 0.6; // квартал: одна громадина или 2×2 башни
      if (!split) {
        const w = 50 + rnd() * 50, dd = 50 + rnd() * 50;
        tower(cx, cz, w, dd, 70 + Math.pow(rnd(), 1.4) * 360 * k, rnd() < 0.65 ? KIND.GLASS : KIND.OFFICE);
        if (rnd() < 0.7) put(cx, cz, Math.min(bw - 2 * m, w + 50), Math.min(bd - 2 * m, dd + 40), 14 + rnd() * 14, KIND.OFFICE); // стилобат
      } else for (let a = 0; a < 2; a++) for (let b = 0; b < 2; b++) {
        if (rnd() < 0.15) continue;
        const qx = x0 + m + (a + 0.5) * (bw - 2 * m) / 2, qz = z0 + m + (b + 0.5) * (bd - 2 * m) / 2;
        const w = 26 + rnd() * 34, dd = 26 + rnd() * 34;
        tower(qx, qz, w, dd, 40 + Math.pow(rnd(), 1.7) * 260 * k, rnd() < 0.5 ? KIND.GLASS : KIND.OFFICE);
      }
    } else if (zn === ZONE.MID) {
      // микрорайон: панельные «пластины» и точечные башни
      const along = rnd() < 0.5, L = (along ? bw : bd) - 2 * m - 20 - rnd() * 30, floors = rnd() < 0.55 ? 9 : rnd() < 0.6 ? 12 : 16;
      const h = floors * 2.9 + 1.5;
      if (along) { put(cx, z0 + m + 7, L, 13, h, KIND.PANEL); put(cx, z1 - m - 7, L * (0.6 + rnd() * 0.4), 13, h, KIND.PANEL); }
      else { put(x0 + m + 7, cz, 13, L, h, KIND.PANEL); put(x1 - m - 7, cz, 13, L * (0.6 + rnd() * 0.4), h, KIND.PANEL); }
      if (rnd() < 0.45) put(cx, cz, 22, 22, 50 + rnd() * 30, KIND.PANEL);
      else if (rnd() < 0.4) put(cx, cz, 34 + rnd() * 20, 26, 9 + rnd() * 5, KIND.PLAIN); // школа, магазин
    } else if (zn === ZONE.LOW || zn === ZONE.FIELD) {
      // частный сектор и пятиэтажки по краям
      const five = d < 8000 && e > 500 && rnd() < 0.35;
      if (five) { put(cx, z0 + m + 6, bw - 2 * m - 30, 12, 15.5, KIND.PANEL); put(cx, z1 - m - 6, bw - 2 * m - 30, 12, 15.5, KIND.PANEL); }
      else for (let a = 0; a < 2; a++) for (let b = 0; b < 2; b++) {
        if (rnd() < 0.18 + 0.5 * (1 - smooth(0, 900, e))) continue; // к краю города и деревни дома редеют
        const qx = x0 + m + (a + 0.5) * (bw - 2 * m) / 2 + (rnd() - 0.5) * 20, qz = z0 + m + (b + 0.5) * (bd - 2 * m) / 2 + (rnd() - 0.5) * 20;
        put(qx, qz, 11 + rnd() * 8, 10 + rnd() * 8, 5 + rnd() * 6, KIND.HOUSE);
      }
    } else if (zn === ZONE.IND || zn === ZONE.PORT) {
      const c = 1 + Math.floor(rnd() * 2);
      for (let q = 0; q < c; q++) {
        const w = 50 + rnd() * (bw - 2 * m - 60), dd = 30 + rnd() * (bd / c - 2 * m - 30);
        const qz = z0 + m + (q + 0.5) * (bd - 2 * m) / c;
        put(cx + (rnd() - 0.5) * (bw - 2 * m - w), qz, w, dd, 8 + rnd() * 12, KIND.WAREHOUSE);
      }
      if (rnd() < 0.12) put(x0 + m + 6, z0 + m + 6, 5, 5, 45 + rnd() * 50, KIND.PLAIN); // заводская труба
    }
    if (!urb[qb] && n > n0) urb[qb] = 1;
  }
  // ── дорожная сеть: улица — вдоль городского квартала, трасса — по каждой 10-й линии до края карты; не по воде (кроме
  //    мостов), не через объекты и аэропорт. Отрезок целиком от перекрёстка до перекрёстка — дорога кончается на перекрёстке.
  // RX[(j+RN)·RS + i+RN] — линия x = i·G, отрезок z ∈ [j·G, (j+1)·G]; RZ — линия z = j·G, отрезок x ∈ [i·G, (i+1)·G]
  const RX = new Uint8Array(RS * RS), RZ = new Uint8Array(RS * RS);
  const ub = (i, j) => (i >= -RN && j >= -RN && i < RN && j < RN ? urb[(j + RN) * RS + i + RN] : 0);
  // у окраинных и деревенских кварталов (1) — не сетка вокруг каждого, а ряды-улицы в одну сторону (своя в каждой округе)
  // и поперечный проезд раз в километр; у городских (2) — улицы со всех сторон
  const rowZ = (x, z) => vnoise(x * 0.00035 + 5.3, z * 0.00035 + 1.7) > 0.5;
  const kind = (a, b, hw, k, alongZ, x, z) => {
    const u = Math.max(a, b);
    if (u === 2) return ROAD.CITY;
    if (hw || (u === 1 && (rowZ(x, z) === alongZ || k % CITY.AVE_EVERY === 0))) return ROAD.RURAL;
    return 0;
  };
  const segOk = (x0, z0, x1, z1, bridge) => {
    for (let t = 0; t <= 1.001; t += 0.1) {
      const x = x0 + (x1 - x0) * t, z = z0 + (z1 - z0) * t;
      if (!bridge && Math.abs(x - riverX(z)) < CITY.RIVER_W / 2 + 12) return false;
      if (Math.abs(x - AIRPORT.x) < AIRPORT.w / 2 + 40 && Math.abs(z - AIRPORT.z) < AIRPORT.d / 2 + 40) return false;
      if (Math.hypot(x, z) > CITY.HALF - 1800) return false;
    }
    return !objects.some((o) => !o.bridge && x1 > o.x - o.w / 2 - 10 && x0 < o.x + o.w / 2 + 10 && z1 > o.z - o.d / 2 - 10 && z0 < o.z + o.d / 2 + 10);
  };
  for (let j = -RN; j < RN; j++) for (let i = -RN; i < RN; i++) {
    const q = (j + RN) * RS + i + RN;
    let t = kind(ub(i - 1, j), ub(i, j), hwy(i), i, true, i * G, (j + 0.5) * G);
    if (t && segOk(i * G, j * G, i * G, (j + 1) * G, false)) RX[q] = t;
    t = kind(ub(i, j - 1), ub(i, j), hwy(j), j, false, (i + 0.5) * G, j * G);
    if (t && segOk(i * G, j * G, (i + 1) * G, j * G, BRIDGE_Z.includes(j * G))) RZ[q] = t;
  }
  // сельские улицы, не связанные с городом или трассой, убираем (отдельный хутор — без асфальта посреди поля)
  {
    const NS = RS + 1, seen = new Uint8Array(NS * NS), st = [];
    const nd = (i, j) => (j + RN) * NS + i + RN;
    for (let j = -RN; j < RN; j++) for (let i = -RN; i < RN; i++) {
      const q = (j + RN) * RS + i + RN;
      if (RX[q] === ROAD.CITY || (RX[q] && hwy(i))) for (const v of [nd(i, j), nd(i, j + 1)]) if (!seen[v]) { seen[v] = 1; st.push(v); }
      if (RZ[q] === ROAD.CITY || (RZ[q] && hwy(j))) for (const v of [nd(i, j), nd(i + 1, j)]) if (!seen[v]) { seen[v] = 1; st.push(v); }
    }
    const go = (v, q, A) => { if (A[q] && !seen[v]) { seen[v] = 1; st.push(v); } };
    while (st.length) {
      const v = st.pop(), i = (v % NS) - RN, j = Math.floor(v / NS) - RN;
      if (i < RN && j < RN) { go(nd(i, j + 1), (j + RN) * RS + i + RN, RX); go(nd(i + 1, j), (j + RN) * RS + i + RN, RZ); }
      if (j > -RN && i < RN) go(nd(i, j - 1), (j - 1 + RN) * RS + i + RN, RX);
      if (i > -RN && j < RN) go(nd(i - 1, j), (j + RN) * RS + i - 1 + RN, RZ);
    }
    for (let j = -RN; j < RN; j++) for (let i = -RN; i < RN; i++) {
      const q = (j + RN) * RS + i + RN;
      if (RX[q] && !seen[nd(i, j)]) RX[q] = 0;
      if (RZ[q] && !seen[nd(i, j)]) RZ[q] = 0;
    }
  }
  const roadT = (i, j, alongZ) => (i < -RN || j < -RN || i >= RN || j >= RN ? 0 : (alongZ ? RX : RZ)[(j + RN) * RS + i + RN]);
  // точка на проезжей части (pad — запас за край, м): для деревьев и фонарей
  const onRoad = (x, z, pad = 0) => {
    const i = Math.round(x / G), j = Math.floor(z / G), t1 = roadT(i, j, true);
    if (t1 && Math.abs(x - i * G) < (t1 === ROAD.CITY ? lineW(i) / 2 : RURAL_HW) + pad) return true;
    const j2 = Math.round(z / G), i2 = Math.floor(x / G), t2 = roadT(i2, j2, false);
    return !!t2 && Math.abs(z - j2 * G) < (t2 === ROAD.CITY ? lineW(j2) / 2 : RURAL_HW) + pad;
  };

  const B = { n, x: BX.subarray(0, n), z: BZ.subarray(0, n), w: BW.subarray(0, n), d: BD.subarray(0, n), h: BH.subarray(0, n), y0: BY.subarray(0, n), k: BK.subarray(0, n), c: BC.subarray(0, n) };
  return { ...mapRuntime(seed, B, objects, groundH), zoneAt, RX, RZ, roadT, onRoad, kind: 'city', airport: AIRPORT };
}


// ═════════════ Общее для карт ═════════════
// сетка высот застройки, грубая сетка максимумов, прямая видимость и луч — по зданиям B, частям объектов и земле gH
// (город — buildCity, зимняя карта — map-winter.js); waterY — уровень воды для луча (у зимней карты лёд — сама земля)
// cellMax(x0, z0, x1, z1) — наибольшая высота земли в ячейке грубой сетки (горы: иначе луч «пролетает» вершину); нет — по 5 точкам
export function mapRuntime(seed, B, objects, gH, waterY = CITY.WATER_Y, cellMax = null) {
  const groundH = gH, n = B.n;
  for (const o of objects) if (!o.bridge && !o.aims) objTargets(o, gH); // точки прицела и площадка (выше)

  // ── сетка высот застройки (над землёй, м) и грубая сетка максимумов (с землёй) ──
  const CELL = CITY.CELL, GN = Math.round(2 * CITY.GH / CELL), grid = new Uint16Array(GN * GN);
  // abs — top — абсолютная высота (часть с y0 — основанием от уровня моря): в ячейку — её превышение над землёй ячейки
  const stamp = (x0, x1, z0, z1, top, abs = false) => {
    const i0 = clamp(Math.floor((x0 + CITY.GH) / CELL), 0, GN - 1), i1 = clamp(Math.floor((x1 + CITY.GH) / CELL), 0, GN - 1);
    const j0 = clamp(Math.floor((z0 + CITY.GH) / CELL), 0, GN - 1), j1 = clamp(Math.floor((z1 + CITY.GH) / CELL), 0, GN - 1);
    const t0 = Math.min(65535, Math.ceil(top));
    for (let j = j0; j <= j1; j++) for (let i = i0; i <= i1; i++) {
      const t = abs ? Math.min(65535, Math.ceil(top - groundH(-CITY.GH + (i + 0.5) * CELL, -CITY.GH + (j + 0.5) * CELL))) : t0, q = j * GN + i;
      if (grid[q] < t) grid[q] = t;
    }
  };
  for (let q = 0; q < n; q++) stamp(B.x[q] - B.w[q] / 2, B.x[q] + B.w[q] / 2, B.z[q] - B.d[q] / 2, B.z[q] + B.d[q] / 2, B.y0[q] + B.h[q]);
  // части с y0 (стена ГЭС, стрелы кранов) — по абсолютной высоте: стена плотины (верх 247 м над морем) ложилась в сетку 248 м НАД землёй —
  // невидимая стена до ~440 м: оружие рвалось в ~190 м над плотиной (ГЭС не повредить), самолёты бились о воздух (2026-10-22). Мосты — как были
  // (настил по сетке ниже настоящего: пролёт под мостом не превращать в столкновение)
  for (const o of objects) for (const p of o.parts) {
    const abs = p.y0 !== undefined && !o.bridge, top = (p.y0 || 0) + p.h;
    if (p.t === 'box') stamp(p.x - p.w / 2, p.x + p.w / 2, p.z - p.d / 2, p.z + p.d / 2, top, abs);
    else stamp(p.x - p.r * 0.85, p.x + p.r * 0.85, p.z - p.r * 0.85, p.z + p.r * 0.85, top, abs);
  }
  const CC = CITY.CC, CN = Math.round(2 * CITY.HALF / CC), coarse = new Float32Array(CN * CN), ratio = CC / CELL;
  for (let j = 0; j < CN; j++) for (let i = 0; i < CN; i++) {
    const x = -CITY.HALF + (i + 0.5) * CC, z = -CITY.HALF + (j + 0.5) * CC;
    let g = -1e9;
    if (cellMax) g = cellMax(x - CC / 2, z - CC / 2, x + CC / 2, z + CC / 2);
    else for (const [ox, oz] of [[0, 0], [-0.5, -0.5], [0.5, -0.5], [-0.5, 0.5], [0.5, 0.5]]) g = Math.max(g, groundH(x + ox * CC, z + oz * CC));
    let b = 0;
    const gi = Math.floor((x - CC / 2 + CITY.GH) / CELL), gj = Math.floor((z - CC / 2 + CITY.GH) / CELL);
    if (gi >= 0 && gj >= 0 && gi + ratio <= GN && gj + ratio <= GN) for (let jj = 0; jj < ratio; jj++) for (let ii = 0; ii < ratio; ii++) b = Math.max(b, grid[(gj + jj) * GN + gi + ii]);
    coarse[j * CN + i] = g + 8 + b; // +8 м — запас на неровность земли внутри ячейки
  }
  const bldAt = (x, z) => {
    const i = Math.floor((x + CITY.GH) / CELL), j = Math.floor((z + CITY.GH) / CELL);
    return i < 0 || j < 0 || i >= GN || j >= GN ? 0 : grid[j * GN + i];
  };
  // верх препятствия в точке: земля + здание
  const topAt = (x, z) => groundH(x, z) + bldAt(x, z);
  // прямая видимость между двумя точками (радар — цель, контейнер — точка): шаг по сетке, высокие участки
  // пролетаем по грубой сетке максимумов. ends — сколько метров у концов не проверять (антенна на крыше, цель в здании)
  function los(ax, ay, az, bx, by, bz, ends = 0) {
    const dx = bx - ax, dy = by - ay, dz = bz - az, L = Math.hypot(dx, dz);
    if (L < 1) return true;
    const step = CELL * 0.75, ns = Math.ceil(L / step), skip = Math.ceil(ends / step);
    for (let s = skip; s <= ns - skip; s++) {
      const t = s / ns, x = ax + dx * t, z = az + dz * t, y = ay + dy * t;
      const ci = Math.floor((x + CITY.HALF) / CC), cj = Math.floor((z + CITY.HALF) / CC);
      if (ci < 0 || cj < 0 || ci >= CN || cj >= CN) continue;
      if (y > coarse[cj * CN + ci]) continue;
      if (y < topAt(x, z)) return false;
    }
    return true;
  }
  // луч из точки o по направлению d (единичный): первая точка на земле, крыше или стене (для прицельного контейнера)
  function raycast(o, d, maxD = 30000, out = { x: 0, y: 0, z: 0 }) {
    const step = CELL * 0.5;
    let px = o.x, py = o.y, pz = o.z;
    for (let s = step; s <= maxD; s += step) {
      const x = o.x + d.x * s, y = o.y + d.y * s, z = o.z + d.z * s;
      const ci = Math.floor((x + CITY.HALF) / CC), cj = Math.floor((z + CITY.HALF) / CC);
      if (ci >= 0 && cj >= 0 && ci < CN && cj < CN && y > coarse[cj * CN + ci]) { px = x; py = y; pz = z; continue; }
      if (y < Math.max(topAt(x, z), waterY)) {
        // уточняем делением пополам между последней свободной точкой и попаданием
        let ax = px, ay = py, az = pz, bx = x, by = y, bz = z;
        for (let k = 0; k < 8; k++) {
          const mx = (ax + bx) / 2, my = (ay + by) / 2, mz = (az + bz) / 2;
          if (my < Math.max(topAt(mx, mz), waterY)) { bx = mx; by = my; bz = mz; } else { ax = mx; ay = my; az = mz; }
        }
        out.x = bx; out.y = by; out.z = bz;
        return out;
      }
      px = x; py = y; pz = z;
    }
    return null;
  }
  // вода (река города; у «Топи» болото — её waterAt): разрыв в воде площадкой объекта не засчитывается (strike.js blast)
  const wetAt = (x, z) => groundH(x, z) < waterY - 0.5;
  return { seed, B, objects, grid, GN, coarse, CN, bldAt, topAt, los, raycast, groundH, wetAt };
}
