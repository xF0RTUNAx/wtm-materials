export function edgeIn(x, z) {
  const n = vnoise(x * 0.0007 + 3.1, z * 0.0007 + 7.7), d = Math.hypot(x - CX, z - CZ);
  return Math.max(CITY.R - 500 + 800 * (n - 0.5) - d, (vnoise(x * 0.0011, z * 0.0011) - 0.78) * 9000);
}
